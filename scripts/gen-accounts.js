// Generates login accounts from scripts/people.json → src/data/accounts.js.
// Run: npm run gen:accounts
// - People already present in accounts.js (same role + ФИО + group) are kept as-is,
//   so re-running never changes anyone's password. Only new people get accounts.
// - The plain passwords of NEWLY created accounts are written once to
//   credentials.local.txt (gitignored) — hand them out, they are not stored anywhere.
// Login/password rules live in src/components/Login/auth.js (loaded here as-is).
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const authSrc = fs.readFileSync(path.join(root, "src/components/Login/auth.js"), "utf8");
const { authCreateAccount } = new Function(authSrc + "\n;return { authCreateAccount };")();

const accountsPath = path.join(root, "src/data/accounts.js");
let accounts = [];
if (fs.existsSync(accountsPath)) {
  accounts = new Function(fs.readFileSync(accountsPath, "utf8") + "\n;return ACCOUNTS;")();
}
const people = JSON.parse(fs.readFileSync(path.join(__dirname, "people.json"), "utf8"));

const sameIdentity = (a, p) => a.role === p.role && a.lastName === p.lastName && a.firstName === p.firstName &&
  a.middleName === p.middleName && a.group === p.group;

(async () => {
  const issued = [];
  for (const p of people) {
    if (accounts.some(a => sameIdentity(a, p))) continue;
    const { account, password, duplicatePerson } = await authCreateAccount(p, accounts);
    accounts.push(account);
    issued.push({ account, password, duplicatePerson });
  }

  const out = "// GENERATED by scripts/gen-accounts.js from scripts/people.json — do not edit by hand.\n" +
    "// Only salted SHA-256 hashes are stored here, never passwords.\n" +
    "const ACCOUNTS = " + JSON.stringify(accounts, null, 2) + ";\n";
  fs.writeFileSync(accountsPath, out);

  if (issued.length) {
    const lines = issued.map(({ account: a, password, duplicatePerson }) =>
      [a.role === "teacher" ? "преп." : a.group, `${a.lastName} ${a.firstName} ${a.middleName}`, a.login, password,
        duplicatePerson ? "⚠ полный тёзка уже есть" : ""].join(" | "));
    fs.writeFileSync(path.join(root, "credentials.local.txt"), lines.join("\n") + "\n", { flag: "a" });
    console.log(lines.join("\n"));
  }
  console.log(`\n${issued.length} new, ${accounts.length} total → src/data/accounts.js`);
})();
